# 2.Take two numbers as input and print their sum, difference, product, quotient, floor division, and modulus.

num1 = float(input("Enter Number 1: "))
num2 = float(input("Enter Number 2: "))

print("Sum: ", num1+num2)
print("Difference: ",num1-num2)
